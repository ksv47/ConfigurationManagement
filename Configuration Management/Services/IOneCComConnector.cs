using Configuration_Management.Models;

namespace Configuration_Management.Services;

/// <summary>
/// Сервис подключения к информационным базам 1С через COM-коннектор
/// (V83.COMConnector / V82 / V81).
/// Позволяет устанавливать соединение и получать информацию о базе.
/// </summary>
public interface IOneCComConnector
{
    /// <summary>
    /// Текст последней ошибки COM-операции (для диагностики в UI).
    /// null — если последняя операция завершилась успешно.
    /// </summary>
    string? LastError { get; }

    /// <summary>
    /// ProgID COM-коннектора, фактически использованный при последнем чтении сведений
    /// о конфигурации (первый предпочтительный кандидат с учётом шаблона имени, issue #175).
    /// Пустая строка, если COM не использовался. Нужен для диагностики в UI (issue #174).
    /// </summary>
    string? LastUsedProgId { get; }

    /// <summary>
    /// Версия платформы базы, по которой разворачивался шаблон имени COM-коннектора
    /// при последнем чтении сведений (issue #174). Пустая строка, если версия не задана.
    /// </summary>
    string? LastUsedPlatformVersion { get; }

    /// <summary>
    /// Устанавливает COM-подключение к информационной базе.
    /// Выполняется в фоновом STA-потоке с ограничением по времени.
    /// Возвращает null, если подключение не удалось или превышен таймаут.
    /// </summary>
    /// <remarks>
    /// ОПАСНО: подключение выполняется в текущем процессе. Под CoreCLR (.NET 5+) вызов
    /// <c>Connect</c> у comcntr.dll обрывает процесс нативным fast-fail (0xC0000409)
    /// без управляемого исключения — перехватить его невозможно, приложение просто исчезает.
    /// Вызывающих в приложении нет; чтение сведений о конфигурации идёт через процесс-агент
    /// (см. ComReadHost). Прежде чем звать этот метод, вынесите COM в тот же агент.
    /// </remarks>
    /// <param name="infobase">Информационная база для подключения.</param>
    /// <param name="timeoutMs">Максимальное время ожидания подключения, мс.</param>
    [Obsolete("Выполняет COM-вызов в текущем процессе: под CoreCLR это обрывает приложение "
              + "нативным fast-fail 0xC0000409 без управляемого исключения. "
              + "Используйте путь через процесс-агент (ComReadHost).")]
    OneCComConnection? Connect(Infobase infobase, int timeoutMs = 8000);

    /// <summary>
    /// Строит строку подключения COM для информационной базы
    /// (File=...; или Srvr=...;Ref=...; + Usr/Pwd при наличии).
    /// </summary>
    string BuildConnectString(Infobase infobase);

    /// <summary>
    /// Считывает наименование и версию конфигурации базы через COM-коннектор.
    /// Возвращает null, если чтение не удалось или превышен таймаут.
    /// </summary>
    OneCConfigInfo? ReadConfigurationInfo(Infobase infobase, int timeoutMs = 8000);
}